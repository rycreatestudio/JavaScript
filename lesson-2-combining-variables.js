/* String Concatenation - Combining Variables
let firstName = "Ryan";
let lastName = "Maharaj";

console.log(firstName + " " + lastName);
*/

/* Arithmetic with Variables

let yearsPlaying = 15;
let yearsPlayingNextYear = yearsPlaying + 1;

console.log(yearsPlayingNextYear);
*/

/* Strings vs Numbers
let firstName = "Ryan";
let lastName = "M";

console.log(firstName + " " + lastName);

*/

/* Arithmetic with Variables - Example 2

let paycheck = 2600; 
let rent = 1450; 

console.log(paycheck - rent);

*/

/* Arithmetic with Variables - Example 3

let x = 20; 
let y = 5;

console.log(x + y);
console.log(x - y);
console.log(x * y);
console.log(x / y);

*/

/* Difference between Strings and Numbers

let age = 30;
let years = 5; 

console.log(age + years);
*/

/* Type coercion - Example 1

let score = "100";
let bonus = 50; 

console.log(score + bonus);

*/

/* Template Literals
let firstName = "Ryan";
let age = 30;
let city = "Tamarac";

console.log("My name is " + firstName + ", I am " + age + " years old, and I live in " + city + ".");
*/

/* Template Literals - Example 2

let firstName = "Ryan";
let age = 30;
let city = "Tamarac";   

console.log(`Hello, my name is ${firstName}, I am ${age} years old, and I live in ${city}.`);

*/

/* Template Literals - Example 3

let firstName = "Ryan";
let age = 30;
let favoriteFood = "Pizza";
let favoriteGame = "Call of Duty";

console.log(`Hello, my name is ${firstName}, I am ${age} years old, and I love to eat ${favoriteFood} while playing ${favoriteGame}.`);

*/
